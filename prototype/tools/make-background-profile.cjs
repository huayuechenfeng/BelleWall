'use strict';
// Firmware-specific, read-only pointer discovery profile. Never patch ROM.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'../..');
const rom=fs.readFileSync(path.join(root,'build/device/rom-fp2/xn3layoutengine.dll'));
const hash=crypto.createHash('sha256').update(rom).digest('hex');
if(hash!=='76d6e4451d657f58a09f8de6313d4aac02c74a42927514b5f266df32730f5816')throw Error('Unsupported ROM; reanalyse layout before generating profile');
const code=fs.readFileSync(path.join(root,'build/device/rom-fp2/xn3layoutengine.code'));
const ranges=[[0x993c,12],[0x231ce,16],[0x31c02,28],[0x3231c,24]];
const checks=ranges.map(([address,length],i)=>{const bytes=code.subarray(address-0x8000,address-0x8000+length);return {address,length,hex:bytes.toString('hex'),index:i};});
let h='// Generated by make-background-profile.cjs. Only ROM '+hash+'\n';
h+='#ifndef BELLE_BACKGROUND_PROFILE_H\n#define BELLE_BACKGROUND_PROFILE_H\n';
for(const c of checks)h+='static const TUint8 KBgFingerprint'+c.index+'[]={'+c.hex.match(/../g).map(x=>'0x'+x).join(',')+'};\n';
h+='static TBool MatchBackgroundCode(TUint base){\n';
for(const c of checks)h+='if(Mem::Compare(reinterpret_cast<const TUint8*>(base+0x'+c.address.toString(16)+'),'+c.length+',KBgFingerprint'+c.index+','+c.length+')!=0)return EFalse;\n';
h+='return ETrue;\n}\n#endif\n';
fs.writeFileSync(path.join(root,'prototype/src/backgroundprofile.h'),h);
fs.writeFileSync(path.join(root,'research/evidence/wallpaper-hook/background-profile.json'),JSON.stringify({hash,viewExportOrdinal:237,viewExportAddress:0x993d,backgroundMemberOffset:0x5c,backgroundVtable:0x40740,drawSlotOffset:0xa4,drawFunction:0x3231d,checks},null,2));
console.log('Generated pinned FP2 background profile');
